package question

import "slices"

// Kind says how a question is answered; it decides the shape of Options
// and CorrectAnswer (migrations/up/036_ma_questions.sql, header). A new
// kind is a new constant + its shape rule, never a schema change.
type Kind string

const (
	KindSingleChoice   Kind = "SINGLE_CHOICE"   // options; exactly one correct option id
	KindMultipleChoice Kind = "MULTIPLE_CHOICE" // options; one or more correct option ids
	KindTrueFalse      Kind = "TRUE_FALSE"      // no options; a boolean value
	KindNumericInput   Kind = "NUMERIC_INPUT"   // no options; the child types a number, matched by value
)

// Kinds lists every kind the bank accepts.
var Kinds = []Kind{KindSingleChoice, KindMultipleChoice, KindTrueFalse, KindNumericInput}

func (k Kind) IsValid() bool { return slices.Contains(Kinds, k) }

// HasOptions reports whether the kind carries an options list.
func (k Kind) HasOptions() bool {
	return k == KindSingleChoice || k == KindMultipleChoice
}

// Source says who wrote a question.
type Source string

const (
	SourceAI    Source = "AI"    // generated by a model, needs review
	SourceAdmin Source = "ADMIN" // typed in by an admin
)

// Review states, stored in question_status.
const (
	StatusPendingReview = "PENDING_REVIEW"
	StatusApproved      = "APPROVED"
	StatusRejected      = "REJECTED"
)

// Option is one choice of a choice question, in display order. Id is short,
// unique within the question and never changes once written: CorrectAnswer
// names options by id, so reordering or rewording never moves the key.
// ImageKey is an S3 object key (presigned on read), nil when text only.
type Option struct {
	Id       string
	Text     string
	ImageKey *string
}

// CorrectAnswer is the key. Exactly one part is used, by kind: OptionIds
// for choice kinds, Value for TRUE_FALSE, Values (canonical numbers, see
// ParseNumber) for NUMERIC_INPUT.
type CorrectAnswer struct {
	OptionIds []string
	Value     *bool
	Values    []string
}
